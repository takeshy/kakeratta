export function lang() {
  const query = new URLSearchParams(globalThis.location?.search || "").get("lang");
  if (query === "ja" || query === "en") return query;
  return /^ja\b/i.test(globalThis.navigator?.language || "ja") ? "ja" : "en";
}

export function t(text, vars) {
  const template = lang() === "en" ? en[text] ?? text : text;
  return vars ? template.replace(/\{(\w+)\}/g, (match, key) => key in vars ? String(vars[key]) : match) : template;
}

// Translates the static text in index.html, which has no template of its own.
export function localizePage(root = document.body) {
  document.documentElement.lang = lang();
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.textContent.trim();
    if (text && en[text]) node.textContent = node.textContent.replace(text, t(text));
  }
  for (const node of root.querySelectorAll("[aria-label]")) node.setAttribute("aria-label", t(node.getAttribute("aria-label")));
}
